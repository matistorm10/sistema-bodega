export const P3_TOTAL_PUNTOS = 420

export type Resp = 'SI' | 'NO' | 'NA' | ''
export type Calificacion = 'Preferente' | 'Condicional' | 'Restringido'

// Igual que la planilla: % = puntos obtenidos / (puntos totales - puntos de los NA)
export function resultadoP3(resp: Record<string, { r?: string }>) {
  let obt = 0, na = 0, sinResp = 0
  for (const it of P3_ITEMS) {
    const r = resp[it.n]?.r
    if (r === 'SI') obt += it.p
    else if (r === 'NA') na += it.p
    else if (r !== 'NO') sinResp++
  }
  const base = P3_TOTAL_PUNTOS - na
  const pct = base > 0 ? (obt / base) * 100 : 0
  const cal: Calificacion = pct >= 95 ? 'Preferente' : pct >= 80 ? 'Condicional' : 'Restringido'
  return { obt, na, base, pct, cal, sinResp }
}
